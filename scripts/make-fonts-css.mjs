/**
 * Generates `src/fonts.css`: the `@font-face` rules of the bundled
 * fonts, from the `@fontsource` packages.
 *
 * The app does not load fonts from the network — offline it would otherwise look
 * different, and every start would send a request to Google. Only the character
 * sets `latin` and `latin-ext` are bundled (the app's four languages and
 * whatever accents entries carry beyond them), and only `woff2`, which every
 * WebView can handle. The packages do not ship a ready-made file for this: their
 * partial files (`latin-400.css`) omit the `unicode-range`, so two of them
 * side by side would cover each other. The script therefore takes the rules from
 * the complete files (`400.css`) and keeps the two character sets.
 *
 * To add a font or a style: add it to `FONTS`, install the package,
 * run `npm run fonts`. The list of selectable fonts is in
 * `src/themes/theme.ts`.
 *
 *   npm run fonts
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** Package → styles, such as `400` or `400-italic`. */
const FONTS = {
  'alegreya': ['400', '500', '600', '400-italic', '500-italic'],
  'cormorant-garamond': ['400', '500', '600', '400-italic', '500-italic'],
  'ibm-plex-sans': ['400', '500', '600', '700'],
  'inter': ['300', '400', '500', '600'],
  'lora': ['400', '500', '600', '400-italic', '500-italic', '600-italic'],
  'merriweather': ['400', '500', '700'],
  'nunito': ['400', '500', '600', '700'],
  'source-sans-3': ['400', '500', '600', '700'],
};

const SUBSETS = ['latin-ext', 'latin'];
const OUT = 'src/fonts.css';

const rules = [];
for (const [pkg, styles] of Object.entries(FONTS)) {
  for (const style of styles) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${style}.css`, 'utf8');
    for (const subset of SUBSETS) {
      const suffix = style.endsWith('-italic') ? style : `${style}-normal`;
      const name = `${pkg}-${subset}-${suffix}`;
      const match = new RegExp(`/\\* ${name} \\*/\\s*(@font-face \\{[^}]*\\})`).exec(css);
      if (!match) throw new Error(`${name} is missing in @fontsource/${pkg}/${style}.css`);
      const rule = match[1]
        // Only woff2, relative to src/ — that way Vite includes the file in the bundle.
        .replace(/src: [^;]*;/, `src: url('../node_modules/@fontsource/${pkg}/files/${name}.woff2') format('woff2');`);
      if (!rule.includes('unicode-range')) throw new Error(`${name} without unicode-range`);
      rules.push(rule);
    }
  }
}

writeFileSync(OUT, `/* Generated by scripts/make-fonts-css.mjs — do not edit by hand. */\n\n${rules.join('\n\n')}\n`);
console.log(`${OUT}: ${rules.length} rules`);
